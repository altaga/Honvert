// Builds src/legal/third-party-notices.js from the license texts that ship inside the
// ffmpeg-kit AAR, so the in-app notices match the binary we actually distribute.
// Usage: node scripts/generate-third-party-notices.js <path/to/ffmpeg-kit-full.aar>
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const FFMPEG_VERSION = "8.1.3";
const FFMPEG_KIT_VERSION = "8.1.9";

const aar = process.argv[2];
if (!aar) {
  console.error("usage: node scripts/generate-third-party-notices.js <ffmpeg-kit-full.aar>");
  process.exit(1);
}

// Component names for the license files in the AAR. The FFmpeg text comes first in the list.
const NAMES = {
  "license.txt": "FFmpeg " + FFMPEG_VERSION + " (ffmpeg-kit build)",
  "license_cpu_features.txt": "cpu_features",
  "license_dav1d.txt": "dav1d",
  "license_expat.txt": "Expat",
  "license_fontconfig.txt": "fontconfig",
  "license_freetype.txt": "FreeType",
  "license_fribidi.txt": "FriBidi",
  "license_harfbuzz.txt": "HarfBuzz",
  "license_kvazaar.txt": "Kvazaar",
  "license_lame.txt": "LAME",
  "license_libaom.txt": "libaom",
  "license_libass.txt": "libass",
  "license_libiconv.txt": "libiconv",
  "license_libilbc.txt": "libilbc",
  "license_libogg.txt": "libogg",
  "license_libpng.txt": "libpng",
  "license_libsndfile.txt": "libsndfile",
  "license_libtheora.txt": "libtheora",
  "license_libuuid.txt": "libuuid",
  "license_libvorbis.txt": "libvorbis",
  "license_libvpx.txt": "libvpx",
  "license_libxml2.txt": "libxml2",
  "license_opencore_amr.txt": "opencore-amr",
  "license_openh264.txt": "OpenH264",
  "license_opus.txt": "Opus",
  "license_sdl.txt": "SDL",
  "license_shine.txt": "Shine",
  "license_snappy.txt": "Snappy",
  "license_soxr.txt": "soxr",
  "license_speex.txt": "Speex",
  "license_twolame.txt": "TwoLAME",
  "license_vo_amrwbenc.txt": "vo-amrwbenc",
  "license_zimg.txt": "zimg",
};

const listing = execFileSync("unzip", ["-l", aar], { encoding: "utf8" });
const entries = listing
  .split("\n")
  .map((line) => line.trim().split(/\s+/).pop())
  .filter((name) => name && name.startsWith("res/raw/license"));

const notices = [];
for (const entry of entries) {
  const file = path.basename(entry);
  const name = NAMES[file];
  if (!name) throw new Error("No component name for " + file + ". Add it to NAMES.");
  const buffer = execFileSync("unzip", ["-p", aar, entry], { maxBuffer: 1 << 26 });
  const text = buffer.toString("utf8").replace(/\r\n/g, "\n").trimEnd();
  notices.push({ name, text });
}

// FFmpeg first, then the rest alphabetically.
notices.sort((a, b) => (a.name.startsWith("FFmpeg") ? -1 : b.name.startsWith("FFmpeg") ? 1 : a.name.localeCompare(b.name)));

const out = `// Generated by scripts/generate-third-party-notices.js from ffmpeg-kit-full ${FFMPEG_KIT_VERSION}.
// Do not edit by hand. Regenerate when the FFmpeg build changes.
export const FFMPEG_VERSION = ${JSON.stringify(FFMPEG_VERSION)};
export const FFMPEG_KIT_VERSION = ${JSON.stringify(FFMPEG_KIT_VERSION)};

export const NOTICES = ${JSON.stringify(notices, null, 1)};
`;

// Run from the project root (npm scripts and the usage line both assume that).
const target = path.resolve(process.cwd(), "src", "legal", "third-party-notices.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log("wrote " + path.relative(process.cwd(), target) + " with " + notices.length + " notices (" + out.length + " bytes)");
